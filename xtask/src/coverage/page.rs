//! The Markdown page of `cargo xtask coverage` (ADR 0074 §2–§4): counts, gap lists and the rule
//! table, rendered from the [`Table`] that `super` builds from the inputs.
//!
//! The page has no clock, no machine and no order of its own. The same table gives the same bytes:
//! `\n` line endings and exactly one final newline.

use super::{CollectorRow, RuleRow, Table};

/// The first line of the page: the warning that the file is generated.
const WARNING: &str = "<!-- Generated by `cargo xtask coverage` from rules/. Do not edit by hand: change the inputs and run the command. -->";
/// The rule statuses, in the order `rule.yaml` lists them.
const STATUSES: [&str; 4] = ["experimental", "test", "stable", "deprecated"];
/// The retention spellings, as `Retention::code` writes them.
const RETENTIONS: [&str; 3] = ["documented", "stated", "none"];
/// The baseline kinds a rule can have, as the page's `baseline` column writes them.
const BASELINES: [&str; 4] = [
    "confronted",
    "known fp",
    "unconfronted",
    "known fp; unconfronted",
];

/// The whole page, rendered from the table. Every line ends with exactly one newline.
pub(super) fn page(table: &Table) -> String {
    let mut out = String::new();
    line(&mut out, WARNING);
    line(&mut out, "");
    line(&mut out, "# Rule coverage");
    line(&mut out, "");
    intro(&mut out, table);
    counts(&mut out, table);
    gaps(&mut out, table);
    rules(&mut out, table);
    out
}

/// Appends one line and its newline.
fn line(out: &mut String, text: &str) {
    out.push_str(text);
    out.push('\n');
}

/// Appends each line of a block, in order.
fn lines(out: &mut String, block: &[&str]) {
    for text in block {
        line(out, text);
    }
}

/// The quoted note, the two explanations of the columns, and the empty-ledger notice when it applies.
fn intro(out: &mut String, table: &Table) {
    lines(
        out,
        &[
            "> Generated by `cargo xtask coverage` from the files listed here: `rules/**/rule.yaml` and their",
            "> `tests/` fixtures, `rules/unconfronted.csv`, `rules/known-fps.csv`, `rules/ages/`, `rules/measured.csv`,",
            "> and the collector list. CI runs `cargo xtask coverage --check`.",
            ">",
            "> The page reports counts and lists and never a percentage or a score (ADR 0074 §3). It is not a",
            "> gate: a gap never fails CI (ADR 0074 §4).",
            "",
            "`confronted` means the rule has no row in `rules/unconfronted.csv`; `cargo xtask check-baseline` fails a rule no baseline confronts that has no row.",
            "",
            "`rules/ages` records whether Microsoft documents a retention (`documented`) or the text states it on other grounds (`stated`); it has no field for a measured retention yet, so `measured` is never shown.",
            "",
        ],
    );
    if table.ledger_collector_rows + table.ledger_rule_rows == 0 {
        lines(
            out,
            &[
                "`rules/measured.csv` has no rows yet; the back-fill from the ADRs is a separate change (ADR 0074, owner decision 3), so the ledger columns read `never` for now.",
                "",
            ],
        );
    }
}

/// The `## Counts` section: plain counts only, no percentages or ratios.
fn counts(out: &mut String, table: &Table) {
    line(out, "## Counts");
    line(out, "");
    count_table(
        out,
        "Rules by status",
        "status",
        &count_by(&table.rows, &STATUSES, |row| row.status),
    );
    count_table(
        out,
        "Rules by baseline",
        "baseline",
        &count_by(&table.rows, &BASELINES, baseline),
    );
    count_table(
        out,
        "Rules by retention",
        "retention",
        &count_by(&table.rows, &RETENTIONS, |row| row.retention.code()),
    );
    let found = table
        .rows
        .iter()
        .filter(|row| !row.seen_found.is_empty())
        .count();
    let never = table.rows.len() - found;
    count_table(out, "Rules seen found", "seen", &[("found", found), ("never", never)]);
    count_table(
        out,
        "Ledger rows by kind",
        "kind",
        &[
            ("collector", table.ledger_collector_rows),
            ("rule", table.ledger_rule_rows),
        ],
    );
}

/// One heading and a two-column table of names and counts, then a blank line.
fn count_table(out: &mut String, heading: &str, first: &str, rows: &[(&str, usize)]) {
    line(out, &format!("### {heading}"));
    line(out, "");
    line(out, &format!("| {first} | count |"));
    line(out, "| --- | ---: |");
    for (name, count) in rows {
        line(out, &format!("| {name} | {count} |"));
    }
    line(out, "");
}

/// How many rules have each of the `names`, by the value `key` gives them.
fn count_by(
    rows: &[RuleRow],
    names: &[&'static str],
    key: fn(&RuleRow) -> &'static str,
) -> Vec<(&'static str, usize)> {
    names
        .iter()
        .map(|name| (*name, rows.iter().filter(|row| key(row) == *name).count()))
        .collect()
}

/// The baseline column of a rule: which baseline lists name it.
fn baseline(row: &RuleRow) -> &'static str {
    match (row.known_fp, row.unconfronted) {
        (false, false) => "confronted",
        (true, false) => "known fp",
        (false, true) => "unconfronted",
        (true, true) => "known fp; unconfronted",
    }
}

/// The `## Gaps` section: each list is headed by its item count, and says `None.` when empty.
fn gaps(out: &mut String, table: &Table) {
    line(out, "## Gaps");
    line(out, "");
    let mut never_seen: Vec<&str> = table
        .rows
        .iter()
        .filter(|row| row.seen_found.is_empty())
        .map(|row| row.dir.as_str())
        .collect();
    never_seen.sort_unstable();
    let never: Vec<String> = never_seen.into_iter().map(ticked).collect();
    section(out, "Rules never seen found outside a fixture", &never);

    let unconfronted: Vec<String> = table
        .unconfronted
        .iter()
        .map(|gap| {
            format!(
                "`{}` — added {}; resolved when: {}",
                gap.dir, gap.added, gap.resolved_when
            )
        })
        .collect();
    section(out, "Rules on the unconfronted list", &unconfronted);

    section(
        out,
        "Collectors never measured",
        &collectors_where(table, |row| row.builds.is_empty()),
    );
    section(
        out,
        "Collectors measured on only one build",
        &collectors_where(table, |row| row.builds.len() == 1),
    );
    section(
        out,
        "Collectors never measured on a client edition",
        &collectors_where(table, |row| !row.builds.is_empty() && !row.client),
    );
    section(
        out,
        "Collectors never measured on Windows 10",
        &collectors_where(table, |row| !row.builds.is_empty() && !row.windows10),
    );
    section(
        out,
        "Collectors never measured without elevation",
        &collectors_where(table, |row| !row.builds.is_empty() && !row.limited),
    );
    section(
        out,
        "Collectors with no `rules/ages` file",
        &collectors_where(table, |row| !row.has_ages),
    );
}

/// The ticked ids of the collectors that `keep` accepts, in table order.
fn collectors_where(table: &Table, keep: fn(&CollectorRow) -> bool) -> Vec<String> {
    table
        .collectors
        .iter()
        .filter(|row| keep(row))
        .map(|row| ticked(&row.id))
        .collect()
}

/// One gap list: a heading with its count, then the bullets or `None.`, then a blank line.
fn section(out: &mut String, title: &str, items: &[String]) {
    line(out, &format!("### {title} ({})", items.len()));
    line(out, "");
    if items.is_empty() {
        line(out, "None.");
    } else {
        for item in items {
            line(out, &format!("- {item}"));
        }
    }
    line(out, "");
}

/// The `## Rules` section: one table, rows in the table's order (collector, then rule directory).
fn rules(out: &mut String, table: &Table) {
    line(out, "## Rules");
    line(out, "");
    line(
        out,
        "| rule | collector | role | strength | status | fixtures | baseline | retention | seen found | measured on |",
    );
    line(
        out,
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for row in &table.rows {
        let cells = [
            ticked(&row.dir),
            row.collector.clone(),
            row.role.to_owned(),
            row.strength.to_owned(),
            row.status.to_owned(),
            format!("{} / {}", row.positive, row.negative),
            baseline(row).to_owned(),
            row.retention.code().to_owned(),
            joined(&row.seen_found),
            joined(&row.measured_on),
        ];
        let escaped: Vec<String> = cells.iter().map(|cell| cell.replace('|', "\\|")).collect();
        line(out, &format!("| {} |", escaped.join(" | ")));
    }
}

/// A name in backticks, as the page writes rule directories and collector ids.
fn ticked(text: &str) -> String {
    format!("`{text}`")
}

/// The items joined with `, `, or `never` when there are none.
fn joined(items: &[String]) -> String {
    if items.is_empty() {
        "never".to_owned()
    } else {
        items.join(", ")
    }
}
